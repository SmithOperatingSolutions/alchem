// Command packaging writes the package-manager manifests for a release from
// its checksums: Formula/alchem.rb, which makes this repository a Homebrew
// tap, and bucket/alchem.json, which makes it a Scoop bucket.
//
//	go run ./tools/packaging -version v0.2.2 -checksums checksums.txt
//
// Without -checksums it downloads the release's checksums.txt from GitHub.
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const (
	repository = "SmithOperatingSolutions/alchem"
	summary    = "Elixir-inspired language compiled to native executables through Go"
)

var tag = regexp.MustCompile(`^v\d+\.\d+\.\d+(-[0-9A-Za-z.]+)?$`)

func main() {
	version := flag.String("version", "", "release tag, such as v0.2.2")
	checksums := flag.String("checksums", "", "the release's checksums.txt; downloaded when not given")
	out := flag.String("dir", ".", "repository root to write Formula/ and bucket/ into")
	flag.Parse()
	if err := run(*version, *checksums, *out); err != nil {
		fmt.Fprintln(os.Stderr, "packaging:", err)
		os.Exit(1)
	}
}

func run(version, checksums, out string) error {
	if !tag.MatchString(version) {
		return fmt.Errorf("-version must be a release tag such as v0.2.2, not %q", version)
	}
	var text io.Reader
	if checksums == "" {
		response, err := http.Get("https://github.com/" + repository + "/releases/download/" + version + "/checksums.txt")
		if err != nil {
			return err
		}
		defer response.Body.Close()
		if response.StatusCode != http.StatusOK {
			return fmt.Errorf("checksums.txt for %s: %s", version, response.Status)
		}
		text = response.Body
	} else {
		file, err := os.Open(checksums)
		if err != nil {
			return err
		}
		defer file.Close()
		text = file
	}
	sums, err := readChecksums(text)
	if err != nil {
		return err
	}
	formula, err := Formula(version, sums)
	if err != nil {
		return err
	}
	manifest, err := Manifest(version, sums)
	if err != nil {
		return err
	}
	for path, content := range map[string]string{"Formula/alchem.rb": formula, "bucket/alchem.json": manifest} {
		target := filepath.Join(out, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(target, []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// readChecksums reads lines of "sha256  file name".
func readChecksums(r io.Reader) (map[string]string, error) {
	sums := map[string]string{}
	lines := bufio.NewScanner(r)
	for lines.Scan() {
		fields := strings.Fields(lines.Text())
		if len(fields) != 2 || len(fields[0]) != 64 {
			continue
		}
		sums[fields[1]] = fields[0]
	}
	return sums, lines.Err()
}

func archive(version, goos, goarch string) string {
	name := "alchem_" + version + "_" + goos + "_" + goarch
	if goos == "windows" {
		return name + ".zip"
	}
	return name + ".tar.gz"
}

func download(version, file string) string {
	return "https://github.com/" + repository + "/releases/download/" + version + "/" + file
}

// Formula is the Homebrew formula for a release.
func Formula(version string, sums map[string]string) (string, error) {
	entry := func(goos, goarch string) (string, error) {
		file := archive(version, goos, goarch)
		sum, ok := sums[file]
		if !ok {
			return "", fmt.Errorf("no checksum for %s", file)
		}
		return fmt.Sprintf("      url %q\n      sha256 %q", download(version, file), sum), nil
	}
	parts := map[string]string{}
	for _, platform := range [][2]string{{"darwin", "arm64"}, {"darwin", "amd64"}, {"linux", "arm64"}, {"linux", "amd64"}} {
		text, err := entry(platform[0], platform[1])
		if err != nil {
			return "", err
		}
		parts[platform[0]+"/"+platform[1]] = text
	}
	return fmt.Sprintf(`# Generated by tools/packaging for %[1]s. Do not edit.
class Alchem < Formula
  desc %[2]q
  homepage "https://github.com/%[3]s"
  version %[4]q
  license "Apache-2.0"

  on_macos do
    on_arm do
%[5]s
    end
    on_intel do
%[6]s
    end
  end

  on_linux do
    on_arm do
%[7]s
    end
    on_intel do
%[8]s
    end
  end

  def install
    bin.install "alchem"
  end

  test do
    assert_match "alchem %[1]s", shell_output("#{bin}/alchem version")
  end
end
`, version, summary, repository, strings.TrimPrefix(version, "v"),
		parts["darwin/arm64"], parts["darwin/amd64"], parts["linux/arm64"], parts["linux/amd64"]), nil
}

// Manifest is the Scoop manifest for a release.
func Manifest(version string, sums map[string]string) (string, error) {
	plain := strings.TrimPrefix(version, "v")
	arch := func(goarch string) (map[string]any, error) {
		file := archive(version, "windows", goarch)
		sum, ok := sums[file]
		if !ok {
			return nil, fmt.Errorf("no checksum for %s", file)
		}
		return map[string]any{"url": download(version, file), "hash": sum, "extract_dir": strings.TrimSuffix(file, ".zip")}, nil
	}
	x64, err := arch("amd64")
	if err != nil {
		return "", err
	}
	arm64, err := arch("arm64")
	if err != nil {
		return "", err
	}
	future := func(goarch string) map[string]any {
		file := "alchem_v$version_windows_" + goarch
		return map[string]any{"url": "https://github.com/" + repository + "/releases/download/v$version/" + file + ".zip", "extract_dir": file}
	}
	manifest := map[string]any{
		"##":           "Generated by tools/packaging for " + version + ". Do not edit.",
		"version":      plain,
		"description":  summary,
		"homepage":     "https://github.com/" + repository,
		"license":      "Apache-2.0",
		"architecture": map[string]any{"64bit": x64, "arm64": arm64},
		"bin":          "alchem.exe",
		"checkver":     map[string]any{"github": "https://github.com/" + repository},
		"autoupdate": map[string]any{
			"architecture": map[string]any{"64bit": future("amd64"), "arm64": future("arm64")},
			"hash":         map[string]any{"url": "$baseurl/checksums.txt"},
		},
	}
	data, err := json.MarshalIndent(manifest, "", "    ")
	if err != nil {
		return "", err
	}
	return string(data) + "\n", nil
}
