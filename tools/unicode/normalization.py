# Generates the tables String.normalize uses, from Python's unicodedata,
# for the Normalization section of compiler/library.go.txt:
#
#   python3 tools/unicode/normalization.py tables.txt
#
# and replace the two constants in that section with the file's contents.
# Use a Python whose unicodedata has the Unicode version of the Go release
# the runtime is built with.
import unicodedata, sys
decomp=[]; ccc=[]; comp=[]
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF: continue
    ch=chr(cp)
    if 0xAC00 <= cp <= 0xD7A3: continue  # Hangul is algorithmic
    c=unicodedata.combining(ch)
    if c: ccc.append((cp,c))
    d=unicodedata.decomposition(ch)
    if not d: continue
    parts=d.split()
    compat = parts[0].startswith('<')
    if compat: parts=parts[1:]
    runes=[int(x,16) for x in parts]
    decomp.append((cp,compat,runes))
    if not compat and len(runes)==2 and unicodedata.normalize('NFC', ''.join(chr(r) for r in runes))==ch:
        comp.append((runes[0],runes[1],cp))
def enc(n): return format(n,'x')
composes=set(c for _,_,c in comp)
d=';'.join(('!' if c else '')+('*' if cp in composes else '')+enc(cp)+':'+' '.join(enc(r) for r in rs) for cp,c,rs in decomp)
cc=';'.join(enc(cp)+':'+str(c) for cp,c in ccc)
print(len(decomp),len(ccc),len(comp),len(d),len(cc),file=sys.stderr)
out=open(sys.argv[1],'w')
out.write('// normDecompositions lists each character with a decomposition, as\n// hex code points; "!" marks a compatibility one and "*" a canonical one\n// that composes back. Hangul syllables are computed instead. Generated by\n// tools/unicode/normalization.py from Unicode %s.\n' % unicodedata.unidata_version)
def chunked(name, text):
    out.write('const %s = ' % name)
    parts=[text[i:i+100] for i in range(0,len(text),100)]
    out.write(' +\n\t'.join('"%s"' % p for p in parts))
    out.write('\n\n')
chunked('normDecompositions', d)
out.write('// normCombining lists the characters with a nonzero canonical combining\n// class.\n')
chunked('normCombining', cc)
