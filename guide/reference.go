package guide

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/SmithOperatingSolutions/alchem/compiler/syntax"
)

const generated = "<!-- Generated by `alchem docs` from the compiler's own tables. Do not edit: change the documentation in the compiler and run `alchem docs` again. -->\n\n"

func anchor(name string) string {
	return strings.ToLower(strings.ReplaceAll(name, " ", "-"))
}

// LibraryReference is docs/library-reference.md.
func LibraryReference() string {
	var b strings.Builder
	b.WriteString("# Library reference\n\n" + generated)
	b.WriteString("Every library function with its signatures, a description and examples; `alchem doc <Module>` and `alchem doc <Module.function>` print the same text. `enum[T]` means any enumerable of `T`: a list, a stream or range, a set, or a map, whose elements are its `tuple[K,V]` entries in key order. Lowercase single names are type variables. Every example is compiled and run by the test suite.\n")
	order, modules := groups(syntax.Modules, func(m syntax.Module) string { return m.Group })
	for _, group := range order {
		b.WriteString("\n**" + group + "**: ")
		var links []string
		for _, module := range modules[group] {
			links = append(links, "["+module.Name+"](#"+anchor(module.Name)+")")
		}
		b.WriteString(strings.Join(links, ", ") + "\n")
	}
	for _, module := range syntax.Modules {
		b.WriteString("\n## " + module.Name + "\n\n" + module.Summary + "\n")
		for _, f := range functionsOf(module.Name) {
			b.WriteString("\n### " + f.Name + "\n\n```\n" + strings.Join(f.Signatures, "\n") + "\n```\n\n" + f.Summary + "\n")
			if len(f.Requires) > 0 {
				b.WriteString("\nRequires: " + strings.Join(f.Requires, "; ") + ".\n")
			}
			if f.Examples != "" {
				b.WriteString("\n```elixir\n" + f.Examples + "\n```\n")
			}
		}
	}
	return b.String()
}

// SyntaxReference is docs/syntax-reference.md.
func SyntaxReference() string {
	var b strings.Builder
	b.WriteString("# Syntax reference\n\n" + generated)
	b.WriteString("One section per topic of `alchem syntax`. Every example is compiled and run by the test suite. The [language specification](language-spec.md) has the full rules.\n")
	order, topics := groups(syntax.Topics, func(t syntax.Topic) string { return t.Group })
	for _, group := range order {
		var links []string
		for _, topic := range topics[group] {
			links = append(links, "["+topic.Name+"](#"+topic.Name+")")
		}
		b.WriteString("\n**" + group + "**: " + strings.Join(links, ", ") + "\n")
	}
	for _, topic := range syntax.Topics {
		b.WriteString("\n" + topicText(topic, "## "))
	}
	return b.String()
}

// CommandReference is docs/cli-reference.md.
func CommandReference() string {
	var b strings.Builder
	b.WriteString("# Command reference\n\n" + generated)
	for _, command := range Commands {
		b.WriteString("## alchem " + command.Name + "\n\n" + command.Summary + "\n\n```\n" + command.Usage + "\n```\n\n")
		if len(command.Flags) > 0 {
			b.WriteString("| Option | Meaning | Default |\n| --- | --- | --- |\n")
			for _, flag := range command.Flags {
				value := ""
				if flag.Default != "" {
					value = "`" + flag.Default + "`"
				}
				fmt.Fprintf(&b, "| `--%s` | %s | %s |\n", flag.Name, flag.Summary, value)
			}
			b.WriteString("\n")
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// References maps each generated file to its content.
func References() map[string]string {
	return map[string]string{
		"library-reference.md": LibraryReference(),
		"syntax-reference.md":  SyntaxReference(),
		"cli-reference.md":     CommandReference(),
		"agent-guide.md":       strings.Replace(AgentGuide(), "\n\n", "\n\n"+generated, 1),
	}
}

// WriteReferences writes the generated files into dir and returns the names
// of those that changed. With check set nothing is written.
func WriteReferences(dir string, check bool) ([]string, error) {
	var changed []string
	for name, text := range References() {
		path := filepath.Join(dir, name)
		if current, err := os.ReadFile(path); err == nil && string(current) == text {
			continue
		}
		changed = append(changed, path)
		if check {
			continue
		}
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
			return nil, err
		}
	}
	sort.Strings(changed)
	return changed, nil
}
