def write(root,files):
    for name,text in files.items():
        path=root/name;path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    return root/'app.alc'


def verify(compiler):
    with tempfile.TemporaryDirectory(prefix='alchem-packages-') as d:
        base=Path(d).resolve();cache=base/'cache'
        for (name,version,sum_),files in PACKAGES.items():
            write(cache/(bundler.escaped(name)+'@'+version),files)
            hashed=cache/'cache/download'/bundler.escaped(name)/'@v'/(version+'.ziphash');hashed.parent.mkdir(parents=True,exist_ok=True);hashed.write_text(sum_)
        built=subprocess.run([str(compiler)],input=(ROOT/'tools/alchem-bundle.alc').read_bytes(),capture_output=True,env={'PATH':''},timeout=120)
        assert (built.returncode,built.stderr)==(0,b''),('bundler build',built.returncode,built.stderr)
        tool=base/'alchem-bundle';tool.unlink(missing_ok=True);tool.write_bytes(built.stdout);tool.chmod(0o700)
        env={'PATH':'','GOMODCACHE':str(cache)};previous=os.environ.get('GOMODCACHE');os.environ['GOMODCACHE']=str(cache)
        try:
            def both(directory,arguments):
                """The native bundler's result, which the Python bundler must equal."""
                done=subprocess.run([str(tool)]+arguments,capture_output=True,cwd=directory,env=env,timeout=120)
                here=os.getcwd();os.chdir(directory)
                try:
                    try:want=(0,bundler.bundle(arguments[-1],arguments[0]=='--locked'),b'')
                    except bundler.BundleError as error:want=(1,b'',f'E_BUNDLE: {error}\n'.encode())
                finally:os.chdir(here)
                assert (done.returncode,done.stdout,done.stderr)==want,(arguments,done.returncode,done.stderr,want[2])
                return done
            # A program of two local files and a package of two: the bundle, the lock and the run.
            project=base/'project';write(project,{'app.alc':APP,'local.alc':LOCAL})
            done=both(project,['app.alc'])
            math=cache/'example.com/!acme/mathkit@v1.2.0/lib/math.alc'
            assert done.stdout.startswith(b'#alchem-bundle 4\n'),done.stdout[:80]
            lock=HEADER+'package example.com/Acme/mathkit v1.2.0 h1:yU/1gISiONnIaSrOPZLtNbOossb9MkwgDU7b9YnT+3M=\n'
            assert (project/'alchem.lock').read_text()==lock,(project/'alchem.lock').read_text()
            image=subprocess.run([str(compiler)],input=done.stdout,capture_output=True,env={'PATH':''},timeout=120)
            assert (image.returncode,image.stderr)==(0,b''),(image.returncode,image.stderr)
            out=base/'out';out.unlink(missing_ok=True);out.write_bytes(image.stdout);out.chmod(0o700)
            run=subprocess.run([str(out)],capture_output=True,env={'PATH':''},timeout=120)
            trace=f'{math}:13:5: pattern match failed\n  at MathKit.first ({math}:13)\n  at App.main ({project}/app.alc:7)\n'.encode()
            assert (run.returncode,run.stdout,run.stderr)==(2,b'43\n',trace),run
            # --locked changes nothing; without an entry it fails; Go module lines of a lock are kept.
            both(project,['--locked','app.alc'])
            (project/'alchem.lock').write_text(lock+'module example.com/x v1.0.0 h1:abc=\n');both(project,['app.alc'])
            assert (project/'alchem.lock').read_text()==HEADER+'module example.com/x v1.0.0 h1:abc=\n'+lock[len(HEADER):],(project/'alchem.lock').read_text()
            (project/'alchem.lock').unlink()
            done=both(project,['--locked','app.alc'])
            assert done.stderr==b'E_BUNDLE: alchem.lock has no entry for example.com/Acme/mathkit@v1.2.0; run without --locked to update it\n' and not (project/'alchem.lock').exists(),done.stderr
            # A program run straight from a package keeps no lock.
            done=both(base,['example.com/Acme/mathkit@v1.2.0/tools/dev.alc'])
            image=subprocess.run([str(compiler)],input=done.stdout,capture_output=True,env={'PATH':''},timeout=120)
            assert (image.returncode,image.stderr)==(0,b''),(image.returncode,image.stderr)
            out.write_bytes(image.stdout)
            run=subprocess.run([str(out)],capture_output=True,env={'PATH':''},timeout=120)
            assert (run.returncode,run.stdout,run.stderr)==(0,b'8\n',b'') and not (base/'alchem.lock').exists(),run
            for index,(files,message) in enumerate(ERRORS):
                done=both(write(base/f'bad{index}',files).parent,['app.alc'])
                assert done.returncode==1 and message.encode() in done.stderr,(message,done.stderr)
        finally:
            if previous is None:del os.environ['GOMODCACHE']
            else:os.environ['GOMODCACHE']=previous
    print(f'PASS packages: a program importing a package from the module cache, its lock file, --locked, a program run from a package, {len(ERRORS)} errors; both bundlers agree')


if __name__=='__main__':verify(Path(sys.argv[1]).resolve())
