def ranges(lines):
    parts=[];i=0
    while i<len(lines):
        j=i
        while j+1<len(lines) and lines[j+1]==lines[j]+1:j+=1
        parts.append(f'{lines[i]}-{lines[j]}' if j>i else str(lines[i]));i=j+1
    return ', '.join(parts)


def report(text,cwd):
    """The pinned runner's report of a cover file (testrunner/tests.go, readCoverage and report)."""
    hits={}
    for line in text.split('\n'):
        fields=line.split('\t')
        if len(fields)!=3:continue
        counts=hits.setdefault(os.path.relpath(fields[0],cwd),{})
        counts[int(fields[1])]=counts.get(int(fields[1]),0)+int(fields[2])
    files=[];lines=covered=0
    for name in sorted(hits):
        counts=hits[name];missed=sorted(n for n,t in counts.items() if t==0)
        files.append((name,len(counts),len(counts)-len(missed),missed));lines+=len(counts);covered+=len(counts)-len(missed)
    total=100*covered/lines if lines else 100.0
    out='\nPercentage | File\n-----------|--------------------------\n'
    for name,count,ran,missed in files:out+='%9.1f%% | %s\n'%(100*ran/count if count else 100.0,name)
    out+='-----------|--------------------------\n%9.1f%% | Total\n'%total
    for name,count,ran,missed in files:
        if missed:out+='\n%s: lines not run: %s\n'%(name,ranges(missed))
    return out


def build(compiler,source,out):
    built=subprocess.run([str(compiler)],input=source,capture_output=True,env={'PATH':''},timeout=300)
    assert (built.returncode,built.stderr)==(0,b''),(source[:200],built.returncode,built.stderr)
    out.write_bytes(built.stdout);out.chmod(0o700)


def verify(compiler):
    with tempfile.TemporaryDirectory(prefix='alchem-failures-') as top:
        out=Path(top)/'out'
        for source,status,stdout,stderr in RUNS:
            build(compiler,source.encode(),out)
            run=subprocess.run([str(out)],capture_output=True,stdin=subprocess.DEVNULL,env={'PATH':''},timeout=120)
            assert (run.returncode,run.stdout,run.stderr)==(status,stdout,stderr),(source,run)
        for index,(files,entry,status,stdout,stderr) in enumerate(TESTS):
            d=Path(top)/f't{index}';d.mkdir()
            for path,text in files.items():
                (d/path).parent.mkdir(parents=True,exist_ok=True);(d/path).write_text(text)
            build(compiler,bundler.bundle(d/entry),d/'out')
            run=subprocess.run([str(d/'out')],capture_output=True,env={'PATH':'','ALCHEM_SEED':'7'},cwd=d,timeout=120)
            seen=(run.returncode,run.stdout.replace(str(d).encode()+b'/',b''),run.stderr.replace(str(d).encode()+b'/',b''))
            assert seen==(status,stdout,stderr),(entry,seen)
        for index,(files,entry,wanted) in enumerate(COVER):
            d=Path(top)/f'c{index}';d.mkdir()
            for path,text in files.items():
                (d/path).parent.mkdir(parents=True,exist_ok=True);(d/path).write_text(text)
            build(compiler,bundler.bundle(d/entry),d/'out')
            # Without the variable nothing is written; with it the file gives the pinned report.
            run=subprocess.run([str(d/'out')],capture_output=True,env={'PATH':'','ALCHEM_SEED':'7'},cwd=d,timeout=120)
            assert run.returncode==0 and not (d/'cover').exists(),(entry,run)
            run=subprocess.run([str(d/'out')],capture_output=True,env={'PATH':'','ALCHEM_SEED':'7','ALCHEM_COVER_FILE':str(d/'cover')},cwd=d,timeout=120)
            assert run.returncode==0 and (d/'cover').stat().st_mode&0o777==0o600,(entry,run)
            seen=report((d/'cover').read_text(),d).encode()
            assert seen==wanted,(entry,seen,wanted)
    print(f'PASS failures: {len(RUNS)} programs of library failures rescued and traced, zero values and ranges, {len(TESTS)} test files with assertion texts, {len(COVER)} coverage reports as the pinned runner prints them')


