#!/usr/bin/env python3
"""Bundle an Alchem entry file and its imports for the self-hosted compiler.

The compiler reads one source from standard input and opens no files. This
follows `import "path.alc"` lines (relative to the importing file) and writes
every module once, the entry first and then each module after the modules
it imports (the order the pinned compiler writes their code in), with each
module's imports rewritten to
`import "module:Name"` on the line of its `defmodule Name do`:

    bundle-alchem.py app.alc | alchem-compiler > app

Every file keeps its lines: an import line becomes an empty one. The bundle
starts with `#alchem-bundle N` and one line `# length path` per file, in
order, giving its length in the bundle and its absolute path, so a failing
program names the file and line it failed in.

A package is imported as the pinned compiler writes it,
`import "host/owner/repo@v1.2.0/lib/file.alc"`, and read from alchem's package
cache (ALCHEM_CACHE, else alchem in the user's cache directory: the packages
`alchem` fetches, tools/alchem-fetch.alc), else from the Go module cache
(GOMODCACHE, else the first GOPATH entry's pkg/mod, else ~/go/pkg/mod). The
bundler does not download. Files of a package import each other with
relative paths that stay inside it, and a program uses one version of a
package. `alchem.lock` beside the entry file records each package's content
hash as the pinned compiler writes it; `--locked` fails instead of updating
it.

Errors mirror the pinned compiler's rules: missing files, import cycles,
duplicate module names, imported modules that define main and files over
1 MiB.
"""
import os
from pathlib import Path
import re
import sys

IMPORT=re.compile(rb'^[ \t]*import[ \t]+"([^"\n]*)"[ \t]*\r?\n?',re.M)
MODULE=re.compile(rb'defmodule[ \t\r\n]+([A-Z][A-Za-z0-9_]*)[ \t\r\n]+do\b')
MAIN=re.compile(rb'^[ \t]*def[ \t]+main[ \t]*\(',re.M)
REMOTE=re.compile(r'^([A-Za-z0-9_~-]+(?:[./][A-Za-z0-9_~-]+)*)@(v[0-9][0-9A-Za-z.+-]*)/([A-Za-z0-9_./-]+\.alc)$')
LOCK='alchem.lock'
LOCK_HEADER='# Generated by alchem. Records the content of remote packages and Go modules; commit this file.\n'


class BundleError(Exception):pass


def directory(lexical):
    return os.path.dirname(lexical)+'/' if '/' in lexical else ''


def escaped(text):
    """A module path or version as the Go module cache spells it."""
    return ''.join('!'+c.lower() if 'A'<=c<='Z' else c for c in text)


def package_cache():
    """alchem's cache, as on Linux (tools/alchem-bundle.alc cache_root), or ''."""
    if os.environ.get('ALCHEM_CACHE'):return os.environ['ALCHEM_CACHE']
    xdg=os.environ.get('XDG_CACHE_HOME','')
    if xdg.startswith('/'):return xdg+'/alchem'
    return os.environ['HOME']+'/.cache/alchem' if os.environ.get('HOME') else ''


def module_cache():
    if 'GOMODCACHE' in os.environ:return os.environ['GOMODCACHE']
    if 'GOPATH' in os.environ:return os.environ['GOPATH'].split(':')[0]+'/pkg/mod'
    return os.environ.get('HOME','')+'/go/pkg/mod'


def remote(target):
    """(module, version, file) of a package import, or None when it is not written as one."""
    match=REMOTE.match(target)
    if not match or '..' in match.group(3) or '//' in match.group(3):return None
    return match.groups()


def sync_lock(entry_lexical,packages,locked):
    """Check the packages against alchem.lock beside the entry and bring it up to date."""
    path=directory(entry_lexical)+LOCK
    try:old=Path(path).read_text()
    except OSError:old=''
    recorded={};modules=[]
    for number,line in enumerate(old.split('\n')):
        fields=line.split()
        if not fields or line.startswith('#'):continue
        if len(fields)==4 and fields[0]=='package':recorded[fields[1]+' '+fields[2]]=fields[3]
        elif len(fields)==4 and fields[0]=='module':modules.append(' '.join(fields[1:]))
        else:raise BundleError(f'{LOCK}:{number+1}: unrecognized line')
    lines=[]
    for key in sorted(packages):
        name=key.replace(' ','@')
        if key in recorded and recorded[key]!=packages[key]:raise BundleError(f'{name} does not match {LOCK}: locked {recorded[key]}, fetched {packages[key]}')
        if key not in recorded and locked:raise BundleError(f'{LOCK} has no entry for {name}; run without --locked to update it')
        lines.append('package '+key+' '+packages[key])
    lines+=['module '+line for line in modules]
    if locked:return
    text=LOCK_HEADER+'\n'.join(sorted(lines))+'\n' if lines else ''
    if text==old:return
    if text:Path(path).write_text(text)
    else:Path(path).unlink()


def bundle(entry,locked=False,limit=1073740799):
    """limit: the most bytes a file may have, which is what a program may have (nc_limit; the pinned compiler reads no file over 1 MiB); None for none."""
    modules=[];names={};loaded={};versions={};packages={}
    def package(path,target):
        """The directory of the package a remote import names, noting its version and hash."""
        parts=remote(target)
        if not parts:raise BundleError(f'{path}: remote imports are written "module/path@v1.2.3/file.alc"')
        module,version,_=parts
        if versions.get(module,version)!=version:raise BundleError(f'{path}: conflicting versions of {module}: {versions[module]} and {version}')
        versions[module]=version
        key=escaped(module)+'@'+escaped(version)
        mine=package_cache()
        if mine:
            try:
                packages[module+' '+version]=Path(mine+'/packages/'+key+'/h1').read_text().strip()
                return os.path.normpath(mine+'/packages/'+key+'/files')
            except OSError:pass
        cache=module_cache()
        try:packages[module+' '+version]=Path(cache+'/cache/download/'+escaped(module)+'/@v/'+escaped(version)+'.ziphash').read_text().strip()
        except OSError:raise BundleError(f'{path}: fetch {module}@{version}: not in the package cache')
        return os.path.normpath(cache+'/'+key)
    def load(path,lexical,root,stack,importer):
        real=path.resolve()
        if real in stack:raise BundleError(f'{importer}: import "{path}": import cycle')
        if real in loaded:return loaded[real]
        try:text=real.read_bytes()
        except OSError as error:raise BundleError(f'{importer}: import "{path}": {error.strerror}')
        if limit is not None and len(text)>limit:raise BundleError(f'{path}: read source: source exceeds {limit} bytes')
        header=MODULE.search(text)
        if not header:raise BundleError(f'{path}: expected defmodule Name do')
        name=header.group(1).decode()
        if name in names:raise BundleError(f'{path}: duplicate module {name} (also {names[name]})')
        if stack and MAIN.search(text):raise BundleError(f'{path}: imported modules cannot define main')
        # The path a failure shows: absolute, cleaned without following links.
        shown=os.path.normpath(os.path.join(os.getcwd(),lexical))
        if '\n' in shown:raise BundleError(f'{path}: path contains a line break')
        names[name]=path;loaded[real]=name
        # The entry first, then every module after those it imports: the order
        # the pinned compiler writes their code in, which its coverage lists follow.
        record={'name':name,'imports':[],'shown':shown}
        if not stack:modules.append(record)
        # Imports are followed in the order of their text, as the pinned compiler does.
        for target in sorted(found.decode() for found in IMPORT.findall(text)):
            if target.startswith('module:'):raise BundleError(f'{path}: import "{target}": only file and package imports are supported')
            if '@' in target:
                inside=package(path,target)
                following=os.path.normpath(inside+'/'+remote(target)[2])
                imported=load(Path(following),following,inside,stack+[real],path)
            else:
                following=os.path.normpath(directory(lexical)+target)
                # A file of a package imports only files of that package.
                if root and not (following+'/').startswith(root+'/'):raise BundleError(f'{path}: import "{target}" leaves the package')
                imported=load(real.parent/target,following,root,stack+[real],path)
            if imported not in record['imports']:record['imports'].append(imported)
        # Lines keep their numbers: an import line leaves an empty one.
        body=IMPORT.sub(lambda match:b'\n' if match.group(0).endswith(b'\n') else b'',text)
        header=MODULE.search(body)
        lines=b''.join(b' import "module:%s"'%imported.encode() for imported in record['imports'])
        record['text']=body[:header.end()]+lines+body[header.end():]
        if stack:modules.append(record)
        return name
    lexical=os.path.normpath(str(entry))
    if remote(str(entry)):
        # A program run straight from a package keeps no lock file.
        inside=package(entry,str(entry));lexical=os.path.normpath(inside+'/'+remote(str(entry))[2])
        load(Path(lexical),lexical,inside,[],entry)
    else:
        load(Path(entry),lexical,'',[],entry)
        sync_lock(lexical,packages,locked)
    texts=[module['text'] if module['text'].endswith(b'\n') else module['text']+b'\n' for module in modules]
    manifest=b'#alchem-bundle %d\n'%len(modules)+b''.join(b'# %d %s\n'%(len(text),module['shown'].encode()) for module,text in zip(modules,texts))
    return manifest+b''.join(texts)



def marked(text):
    """A bundle, or the text of one file, marked as of the build: its modules
    whose names start with Alchem may call what only the library may
    (nc_ours). alchem marks no program."""
    if not text.startswith(b'#alchem-bundle '):
        text = text if text.endswith(b'\n') else text + b'\n'
        text = b'#alchem-bundle 1\n# %d <stdin>\n' % len(text) + text
    head, _, rest = text.partition(b'\n')
    return head + b'\x7f\n' + rest


def main():
    arguments=sys.argv[1:];locked=arguments[:1]==['--locked']
    if len(arguments)!=1+locked:
        sys.stderr.write('Usage: bundle-alchem.py [--locked] ENTRY.alc\n');return 2
    try:output=bundle(arguments[-1],locked)
    except BundleError as error:
        sys.stderr.write(f'E_BUNDLE: {error}\n');return 1
    sys.stdout.buffer.write(output);return 0


if __name__=='__main__':sys.exit(main())
