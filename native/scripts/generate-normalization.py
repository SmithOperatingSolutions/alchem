#!/usr/bin/env python3
"""Regenerate the String.normalize entry at the end of library/String.alc.

The tables are the pinned runtime's own (compiler/library.go.txt in the
module cache: normDecompositions and normCombining, which upstream made
from Unicode 17.0.0 with its tools/unicode/normalization.py), so the native
function decomposes, orders and composes exactly the characters upstream
does. Not used by normal builds; run scripts/generate-prelude.py after it.

The tables are text, in pieces a `case` picks, so that no table is one
long literal and reading one allocates nothing (a string literal lies in
the program's image):

  nm_d   one record of 12 digits for each character with a
         decomposition, in order of code point: the code point (4), then
         where its full canonical decomposition starts in nm_e (3) and how
         many code points it has (1, 0 when it has none), then the same for
         the full compatibility decomposition
  nm_e   the decompositions, 4 digits a code point
  nm_c   6 digits for each character with a combining class: the code
         point (4) and the class (2)
  nm_p   12 digits for each pair that composes, in order: the two code
         points and what they make

A digit is one of 64 characters (six bits, the most significant first):
the 44 from "0" to "[" and the 20 from "]" to "p", so that no table holds
a quote, a backslash or a "#".
"""
from pathlib import Path
import re
import sys

sys.path.insert(0,str(Path(__file__).resolve().parent))
import reference

ROOT=Path(__file__).resolve().parents[1]
UPSTREAM=reference.tree()/'compiler/library.go.txt'
TARGET=ROOT/'library/String.alc'
BEGIN='# String.normalize: generated by scripts/generate-normalization.py from the pinned runtime\'s tables (Unicode 17.0.0); do not edit below.\n'
PIECE=2000


def digits(value,count):
    return ''.join(chr(48+d if d<44 else 49+d) for d in [(value>>(6*(count-1-i)))&63 for i in range(count)])


def constant(text,name):
    start=text.index('const '+name+' = ')
    end=text.index('\n\n',start)
    return ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"',text[start:end]))


def tables():
    text=UPSTREAM.read_text()
    decompose={};compat={};compose={}
    for entry in constant(text,'normDecompositions').split(';'):
        key,value=entry.split(':')
        r=int(key.lstrip('!*'),16);runes=[int(p,16) for p in value.split()]
        decompose[r]=runes;compat[r]=key.startswith('!')
        if '*' in key:compose[(runes[0],runes[1])]=r
    combining={int(k,16):int(v) for k,v in (e.split(':') for e in constant(text,'normCombining').split(';'))}
    def full(r,wide):
        if r in decompose and (wide or not compat[r]):return [x for p in decompose[r] for x in full(p,wide)]
        return [r]
    return decompose,compat,compose,combining,full


def pieces(name,text,width):
    size=PIECE-PIECE%width
    parts=[text[i:i+size] for i in range(0,len(text),size)] or ['']
    lines=['  defp '+name+'(k: integer): string do\n','    case k do\n']
    for i,part in enumerate(parts[:-1]):lines.append('      %d -> "%s"\n'%(i,part))
    lines.append('      _ -> "%s"\n'%parts[-1])
    lines+=['    end\n','  end\n']
    return ''.join(lines),size//width


def generate():
    decompose,compat,compose,combining,full=tables()
    e='';d=''
    for r in sorted(decompose):
        narrow=[] if compat[r] else full(r,False)
        wide=full(r,True)
        assert len(wide)<64
        d+=digits(r,4)+digits(len(e)//4,3)+digits(len(narrow),1);e+=''.join(digits(x,4) for x in narrow)
        d+=digits(len(e)//4,3)+digits(len(wide),1);e+=''.join(digits(x,4) for x in wide)
    c=''.join(digits(r,4)+digits(combining[r],2) for r in sorted(combining))
    p=''.join(digits(a,4)+digits(b,4)+digits(compose[(a,b)],4) for a,b in sorted(compose))
    out=[BEGIN]
    counts={}
    for name,text,width in [('nm_d',d,12),('nm_e',e,4),('nm_c',c,6),('nm_p',p,12)]:
        code,per=pieces(name,text,width);out.append(code);counts[name]=(len(text)//width,per)
    code=CODE
    for name,(count,per) in counts.items():code=code.replace(name.upper()+'_COUNT',str(count)).replace(name.upper()+'_PER',str(per))
    source=TARGET.read_text()
    if BEGIN in source:source=source[:source.index(HEAD)]
    TARGET.write_text(source.rstrip('\n')+'\n'+HEAD+code+''.join(out[1:]))


HEAD=BEGIN+'#: normalize/2 needs Sys.rune/2 Sys.pad/0 Sys.push/2 Sys.got/0 Enum.sort_by/2 Enum.reverse/1\n'
CODE='''  def normalize(text: string, form: atom): string do
    mode = if form == :nfd do 0 else if form == :nfc do 1 else if form == :nfkd do 2 else if form == :nfkc do 3 else raise("String.normalize takes :nfc, :nfd, :nfkc or :nfkd") end end end end
    if nm_simple(Sys.addr(text), byte_size(text)) do text else
      none: list[integer] = []
      runes = nm_ordered(nm_runes(Sys.addr(text), byte_size(text), mode / 2, none))
      made = if mode % 2 == 1 do nm_composed(runes) else runes end
      s = Sys.pad()
      nm_text(made)
    end
  end
  # true for text that is ASCII with no carriage return, which is returned as it is.
  defp nm_simple(a: integer, n: integer): boolean do
    if n == 0 do true else
      b = Sys.byte(a)
      if b >= 128 or b == 13 do false else nm_simple(a + 1, n - 1) end
    end
  end
  # The value of n digits of six bits at a.
  defp nm_hex(a: integer, n: integer, v: integer): integer do
    if n == 0 do v else
      b = Sys.byte(a)
      nm_hex(a + 1, n - 1, v * 64 + (if b < 92 do b - 48 else b - 49 end))
    end
  end
  defp nm_da(i: integer): integer do Sys.addr(nm_d(i / NM_D_PER)) + (i % NM_D_PER) * 12 end
  defp nm_ea(i: integer): integer do Sys.addr(nm_e(i / NM_E_PER)) + (i % NM_E_PER) * 4 end
  defp nm_ca(i: integer): integer do Sys.addr(nm_c(i / NM_C_PER)) + (i % NM_C_PER) * 6 end
  defp nm_pa(i: integer): integer do Sys.addr(nm_p(i / NM_P_PER)) + (i % NM_P_PER) * 12 end
  # The record of r in nm_d between lo and hi, -1 for none.
  defp nm_find(r: integer, lo: integer, hi: integer): integer do
    if lo >= hi do -1 else
      m = (lo + hi) / 2
      x = nm_hex(nm_da(m), 4, 0)
      if x == r do m else if x < r do nm_find(r, m + 1, hi) else nm_find(r, lo, m) end end
    end
  end
  # The combining class of r.
  defp nm_class(r: integer, lo: integer, hi: integer): integer do
    if lo >= hi do 0 else
      m = (lo + hi) / 2
      x = nm_hex(nm_ca(m), 4, 0)
      if x == r do nm_hex(nm_ca(m) + 4, 2, 0) else if x < r do nm_class(r, m + 1, hi) else nm_class(r, lo, m) end end
    end
  end
  # What a and b compose to, -1 for nothing.
  defp nm_pair(a: integer, b: integer, lo: integer, hi: integer): integer do
    if lo >= hi do -1 else
      m = (lo + hi) / 2
      x = nm_hex(nm_pa(m), 4, 0)
      y = nm_hex(nm_pa(m) + 4, 4, 0)
      if x == a and y == b do nm_hex(nm_pa(m) + 8, 4, 0) else if x < a or (x == a and y < b) do nm_pair(a, b, m + 1, hi) else nm_pair(a, b, lo, m) end end
    end
  end
  # n code points of nm_e from i put before done, which is kept in reverse.
  defp nm_take(i: integer, n: integer, done: list[integer]): list[integer] do
    if n == 0 do done else nm_take(i + 1, n - 1, [nm_hex(nm_ea(i), 4, 0) | done]) end
  end
  # r decomposed, put before done: a Hangul syllable by arithmetic, any
  # other by the table. wide: 1 for the compatibility decompositions.
  defp nm_apart(r: integer, wide: integer, done: list[integer]): list[integer] do
    s = r - 44032
    if s >= 0 and s < 11172 do
      lv = [4449 + (s % 588) / 28, 4352 + s / 588 | done]
      if s % 28 == 0 do lv else [4519 + s % 28 | lv] end
    else
      at = nm_find(r, 0, NM_D_COUNT)
      if at < 0 do [r | done] else
        a = nm_da(at) + 4 + wide * 4
        n = nm_hex(a + 3, 1, 0)
        if n == 0 do [r | done] else nm_take(nm_hex(a, 3, 0), n, done) end
      end
    end
  end
  # The code points of the n bytes at a, decomposed, in reverse. A byte
  # that is no UTF-8 is U+FFFD, as Go ranges over a string.
  defp nm_runes(a: integer, n: integer, wide: integer, done: list[integer]): list[integer] do
    if n == 0 do done else
      u = Sys.rune(a, n)
      k = if u == 0 do 1 else u / 2097152 end
      nm_runes(a + k, n - k, wide, nm_apart(if u == 0 do 65533 else u % 2097152 end, wide, done))
    end
  end
  # Canonical ordering: the marks between two starters in the order of
  # their classes, those of one class as they stood. The list comes in
  # reverse and leaves in order.
  defp nm_ordered(runes: list[integer]): list[integer] do
    none: list[integer] = []
    no: list[tuple[integer, integer]] = []
    nm_sorted(Enum.reverse(runes), no, none)
  end
  # held: the marks since the last starter, in reverse, each with its class.
  defp nm_sorted(runes: list[integer], held: list[tuple[integer, integer]], done: list[integer]): list[integer] do
    if runes == [] do Enum.reverse(nm_flush(held, done)) else
      r = hd(runes)
      c = nm_class(r, 0, NM_C_COUNT)
      if c == 0 do nm_sorted(tl(runes), [], [r | nm_flush(held, done)]) else nm_sorted(tl(runes), [{c, r} | held], done) end
    end
  end
  defp nm_flush(held: list[tuple[integer, integer]], done: list[integer]): list[integer] do
    if held == [] do done else
      Enum.reduce(Enum.sort_by(Enum.reverse(held), fn p -> elem(p, 0) end), done, fn p, all -> [elem(p, 1) | all] end)
    end
  end
  # Canonical composition, as the pinned runtime's normCompose: a starter
  # takes the marks after it that compose with it and are not blocked.
  defp nm_composed(runes: list[integer]): list[integer] do
    if runes == [] do runes else
      none: list[integer] = []
      first = hd(runes)
      nm_join(tl(runes), {first, if nm_class(first, 0, NM_C_COUNT) != 0 do 255 else 0 end}, none, none)
    end
  end
  # state: the starter and the class of the last mark kept (255 before any
  # starter); marks: what stands after the starter, in reverse; before:
  # what stands before it, in reverse.
  defp nm_join(runes: list[integer], state: tuple[integer, integer], marks: list[integer], before: list[integer]): list[integer] do
    s = elem(state, 0)
    last = elem(state, 1)
    if runes == [] do Enum.reverse(marks ++ [s | before]) else
      r = hd(runes)
      c = nm_class(r, 0, NM_C_COUNT)
      l = s - 4352
      lv = s - 44032
      made = nm_pair(s, r, 0, NM_P_COUNT)
      if l >= 0 and l < 19 and r >= 4449 and r < 4470 and marks == [] do nm_join(tl(runes), {44032 + (l * 21 + (r - 4449)) * 28, last}, marks, before) else
        if lv >= 0 and lv < 11172 and lv % 28 == 0 and r > 4519 and r < 4547 and marks == [] do nm_join(tl(runes), {s + (r - 4519), last}, marks, before) else
          if made >= 0 and (last < c or (last == 0 and marks == [])) and last != 255 do nm_join(tl(runes), {made, last}, marks, before) else
            if c == 0 do nm_join(tl(runes), {r, 0}, [], marks ++ [s | before]) else nm_join(tl(runes), {s, c}, [r | marks], before) end
          end
        end
      end
    end
  end
  # The code points as UTF-8, on the pad.
  defp nm_text(runes: list[integer]): string do
    if runes == [] do Sys.got() else
      r = hd(runes)
      w = if r < 128 do Sys.push(r, 1) else
        if r < 2048 do Sys.push(192 + r / 64 + (128 + r % 64) * 256, 2) else
          if r < 65536 do Sys.push(224 + r / 4096 + (128 + (r / 64) % 64) * 256 + (128 + r % 64) * 65536, 3) else
            Sys.push(240 + r / 262144 + (128 + (r / 4096) % 64) * 256 + (128 + (r / 64) % 64) * 65536 + (128 + r % 64) * 16777216, 4)
          end
        end
      end
      nm_text(tl(runes))
    end
  end
'''

if __name__=='__main__':generate()
