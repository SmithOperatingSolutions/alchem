#!/usr/bin/env python3
"""Generate implementations/alchem/native-marked-data.alc: the x86-64 fragments
that hold data among their code, assembled once more with the marker the ARM64
compiler's translation reads (0F 0B 'D', the length, 0) before each
RIP-relative instruction that names data (native-x86arm.alc, xa_mark). The
assembler places the markers, so every jump around them stays right; the
ARM64 compiler emits these where the x86-64 compiler emits the plain ones
(spec/arm64.md)."""
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def marked(text):
    """text with a marker before each RIP-relative operand that names a data
    label: one whose definition is followed (on its line or the next) by
    .ascii or .byte. A numeric label NNf is the next NN after the line, NNb
    the last before it."""
    lines = text.split('\n')
    data = {}            # line of a label's definition -> the data's size
    defs = []            # (line, name)
    for index, line in enumerate(lines):
        m = re.match(r'^\s*(\w+):\s*(.*)$', line)
        if not m:
            continue
        defs.append((index, m.group(1)))
        rest = m.group(2).strip() or (lines[index + 1].strip() if index + 1 < len(lines) else '')
        d = re.match(r'\.(ascii|byte)\s+(.*)$', rest)
        if d:
            data[index] = len(eval(d.group(2))) if d.group(1) == 'ascii' else len(d.group(2).split(','))
    out = []
    for index, line in enumerate(lines):
        m = re.search(r'\[rip\+(\w+?)([fb]?)\]', line)
        if m:
            name, way = m.group(1), m.group(2)
            if way == 'f':
                found = next((i for i, n in defs if i > index and n == name), None)
            elif way == 'b':
                found = next((i for i, n in reversed(defs) if i < index and n == name), None)
            else:
                found = next((i for i, n in defs if n == name), None)
            if found in data:
                out.append(f' .byte 0x0f,0x0b,0x44\n .long {data[found]}\n .long 0')
        out.append(line)
    return '\n'.join(out)


def assemble(text, section=None):
    with tempfile.TemporaryDirectory(prefix='alchem-marked-') as d:
        root = Path(d)
        (root / 'f.s').write_text(text)
        subprocess.run(['as', '--64', '-o', str(root / 'f.o'), str(root / 'f.s')], check=True)
        subprocess.run(['objcopy', '-O', 'binary', '--only-section=' + (section or '.text'), str(root / 'f.o'), str(root / 'f.bin')], check=True)
        return (root / 'f.bin').read_bytes()


def symbols(text):
    """The offsets in .text of the labels of text."""
    with tempfile.TemporaryDirectory(prefix='alchem-marked-') as d:
        root = Path(d)
        (root / 'f.s').write_text(text)
        subprocess.run(['as', '--64', '-o', str(root / 'f.o'), str(root / 'f.s')], check=True)
        listing = subprocess.run(['nm', str(root / 'f.o')], capture_output=True, text=True, check=True).stdout
        return {line.split()[2]: int(line.split()[0], 16) for line in listing.splitlines() if len(line.split()) == 3}


def compiler_io():
    """The input and output of a compiler entry (spec/compiler-io-x86_64.s),
    marked: the part before the call of native_compile and the part after
    it. The plain assembly must be what native-runtime.alc emits."""
    source = (ROOT / 'spec/compiler-io-x86_64.s').read_text()
    plain, at = assemble(source), symbols(source)['io_call']
    runtime = (ROOT / 'implementations/alchem/native-runtime.alc').read_text()
    def emitted(name):
        return bytes(int(x) for x in re.search(r'def ' + name + r'\(\): bytes do\n(?:    #.*\n)*    b\[([0-9,]*)\]', runtime).group(1).split(','))
    if plain[:at] != emitted('nc_io_prefix') or plain[at + 9:] != b''.join(emitted(f'nc_io_part{i}') for i in range(4)):
        raise SystemExit('spec/compiler-io-x86_64.s is not what native-runtime.alc emits')
    text = marked(source)
    raw, at = assemble(text), symbols(text)['io_call']
    return raw[:at], raw[at + 9:]


def literal(raw):
    if len(raw) <= 128:
        return 'b[' + ','.join(map(str, raw)) + ']'
    middle = len(raw) // 2
    return 'Enum.concat(' + literal(raw[:middle]) + ',' + literal(raw[middle:]) + ')'


def main():
    library = marked((ROOT / 'spec/library-x86_64.s').read_text())
    failures = marked((ROOT / 'spec/failures-x86_64.s').read_text())
    before, after = compiler_io()
    pieces = {'na_pad_emit_marked': assemble(library, '.text.na_pad'), 'zf_slice_check_marked': assemble(failures),
              'nc_io_prefix_marked': before, 'nc_io_suffix_marked': after}
    text = 'defmodule NativeMarkedData do\n  # Generated by scripts/generate-marked-fragments.py (spec/arm64.md).\n'
    for name, raw in pieces.items():
        parts = [raw[i:i + 384] for i in range(0, len(raw), 384)]
        for index, part in enumerate(parts):
            text += f'  def {name}_{index}(): bytes do {literal(part)} end\n'
        calls = [f'{name}_{index}()' for index in range(len(parts))]
        while len(calls) > 1:
            calls = ['Enum.concat(' + calls[0] + ',' + calls[1] + ')'] + calls[2:]
        text += f'  def {name}(): bytes do {calls[0]} end\n'
        print(name, len(raw))
    text += '  # Native smoke test; generated marked fragments.\n  def main() do System.halt(0) end\nend\n'
    (ROOT / 'implementations/alchem/native-marked-data.alc').write_text(text)


if __name__ == '__main__':
    main()
