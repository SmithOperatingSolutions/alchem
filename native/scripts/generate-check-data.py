#!/usr/bin/env python3
"""Write tools/alchem-check-data.alc: the tables the pinned checker types a
program's calls with (syntax.Libraries, Overloads, SimpleBuiltins and
BuiltinTypes), as scripts/pinned-checkdata prints them from the pinned
module. Not used by normal builds: run again when the pin moves.

    generate-check-data.py"""
from pathlib import Path
import os
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from importlib.util import module_from_spec, spec_from_file_location

spec = spec_from_file_location('guide_data', ROOT / 'scripts/generate-guide-data.py')
guide = module_from_spec(spec)
spec.loader.exec_module(guide)

HEADER = '''defmodule AlchemCheckData do
  # Generated by scripts/generate-check-data.py from the pinned checker's
  # tables; do not edit. One record a line, fields apart by \\u{1F} and
  # lists by \\u{1E}:
  #
  #   L key name params result vars equal order show keys num cal codec read
  #   O key further-keys
  #   S name params result
  #   T kind name local params fields variants (name\\u{1D}field:type...)
'''


def main():
    environment = dict(os.environ, GOFLAGS='-mod=mod', GOPROXY='off')
    done = subprocess.run(['go', 'run', '.'], cwd=ROOT / 'scripts/pinned-checkdata', capture_output=True, text=True, env=environment, check=True)
    lines = done.stdout.rstrip('\n').split('\n')
    text = HEADER + '  def records(): string do\n    ' + guide.literal('\n'.join(lines)) + '\n  end\nend\n'
    (ROOT / 'tools/alchem-check-data.alc').write_text(text)
    print(f'wrote tools/alchem-check-data.alc: {len(lines)} records')


if __name__ == '__main__':
    main()
