#!/usr/bin/env python3
"""Regenerate the zone database built into the library (library/Date.alc,
between the markers): Go's time/tzdata as the pinned Go toolchain has it
(lib/time/zoneinfo.zip of `go env GOROOT`), which the pinned compiler's
programs carry. Optional development step; normal builds never run it.

What is kept is one deflate stream (RFC 1951), in base64: a count of
zones (4 bytes, high first), then each zone's name (a length byte and
the name), where its file starts after the index and its length (4 bytes
each), then the files, in the zip's order (spec/alchem-time-zones.md)."""
import base64
from pathlib import Path
import struct
import subprocess
import sys
import zipfile
import zlib

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '# BEGIN generated by scripts/generate-tzdata.py\n'
END = '# END generated by scripts/generate-tzdata.py\n'


def database():
    goroot = subprocess.run(['go', 'env', 'GOROOT'], capture_output=True, text=True, check=True, cwd=ROOT).stdout.strip()
    with zipfile.ZipFile(Path(goroot) / 'lib/time/zoneinfo.zip') as z:
        names = z.namelist()
        files = [z.read(n) for n in names]
    index = struct.pack('>I', len(names))
    at = 0
    for name, data in zip(names, files):
        encoded = name.encode()
        assert len(encoded) < 256
        index += bytes([len(encoded)]) + encoded + struct.pack('>II', at, len(data))
        at += len(data)
    raw = index + b''.join(files)
    deflate = zlib.compressobj(9, zlib.DEFLATED, -15)
    packed = deflate.compress(raw) + deflate.flush()
    return base64.b64encode(packed).decode(), len(names), len(raw), len(packed)


def main():
    text, count, raw, packed = database()
    path = ROOT / 'library/Date.alc'
    source = path.read_text()
    start = source.index(BEGIN) + len(BEGIN)
    stop = source.index(END)
    body = f'  defp tzdata(): string do\n    "{text}"\n  end\n'
    path.write_text(source[:start] + body + source[stop:])
    print(f'{count} zones: {raw:,} bytes, {packed:,} deflated', file=sys.stderr)


if __name__ == '__main__':
    main()
