#!/usr/bin/env python3
"""Generate implementations/alchem/native-runtimes-arm64.alc: the ARM64 version
of each runtime that is a table entry of its own (spec/arm64.md). Each
runtime's own generator is run with the assembler watched: the assembly it
hands to `as` is what is translated (scripts/x86-to-arm64.py) and assembled
for ARM64, so a runtime's x86-64 source and the data its generator adds stay
the one source of both versions.
"""
from importlib.util import module_from_spec, spec_from_file_location
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import arm64_runtime  # noqa: E402

# (generator, the blob names of the sources it assembles, in order)
RUNTIMES = [('trace-runtime', ['tr']), ('float-runtime', ['fl']), ('crypto-runtime', ['kr']), ('tls-runtime', ['tq']),
            ('parse-runtime', ['ip']), ('file-read-runtime', ['fr']), ('case-runtime', ['cm']), ('grapheme-runtime', ['ng'])]


def sources(generator):
    """The assembly texts the generator gives to as, in order."""
    seen = []
    real = subprocess.run

    def watching(command, *args, **kwargs):
        if isinstance(command, list) and command and command[0] == 'as':
            seen.append(Path(command[-1]).read_text())
        return real(command, *args, **kwargs)
    subprocess.run = watching
    try:
        spec = spec_from_file_location('generator', ROOT / f'scripts/generate-{generator}.py')
        module = module_from_spec(spec)
        spec.loader.exec_module(module)
        module.generate()
    finally:
        subprocess.run = real
    return seen


# Runtimes the compiler holds as bytes of an assembly source of its own,
# translated with ARM defined: (source, blob name).
FILES = [('spec/cover-x86_64.s', 'cv')]


def main():
    functions = []
    for path, name in FILES:
        data = arm64_runtime.assemble((ROOT / path).read_text(), ('ARM',))
        body = arm64_runtime.module_text('X', f'{name}_blob_arm', data, path).split('\n')
        functions.append(next(line for line in body if line.startswith(f'  def {name}_blob_arm()')))
        print(f'{name}: {len(data)} bytes')
    for generator, names in RUNTIMES:
        texts = sources(generator)
        assert len(texts) == len(names), (generator, len(texts))
        for name, text in zip(names, texts):
            data = arm64_runtime.assemble(text, ('ARM',))
            body = arm64_runtime.module_text('X', f'{name}_blob_arm', data, generator).split('\n')
            functions.append(next(line for line in body if line.startswith(f'  def {name}_blob_arm()')))
            print(f'{name}: {len(data)} bytes')
    text = ('defmodule NativeRuntimesArm64 do\n  # Generated by scripts/generate-arm64-runtimes.py: the ARM64 version of each\n'
            '  # runtime that is a table entry of its own (spec/arm64.md).\n' + '\n'.join(functions) +
            '\n  # Native smoke test; generated ARM64 runtimes.\n  def main() do System.halt(0) end\nend\n')
    (ROOT / 'implementations/alchem/native-runtimes-arm64.alc').write_text(text)


if __name__ == '__main__':
    main()
