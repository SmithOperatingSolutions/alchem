// Command pinned-print writes tools/alchem-print-data.alc: the runes Go's
// strconv.Quote writes as escapes because strconv.IsPrint says they are not
// printable, by the Unicode tables of the Go that runs it. Run it with the
// pinned toolchain from the native directory:
//
//	(cd scripts/pinned-print && go run .) > tools/alchem-print-data.alc
package main

import (
	"fmt"
	"strconv"
	"strings"
)

func main() {
	var ranges strings.Builder
	count, start := 0, -1
	for r := 0; r <= 0x110000; r++ {
		// Surrogates never come out of decoding, so they need no place.
		printable := r == 0x110000 || strconv.IsPrint(rune(r)) || (r >= 0xD800 && r < 0xE000)
		if !printable && start < 0 {
			start = r
		}
		if printable && start >= 0 {
			fmt.Fprintf(&ranges, "%06x%06x", start, r-1)
			count++
			start = -1
		}
	}
	fmt.Println("defmodule AlchemPrintData do")
	fmt.Println("  # Generated by scripts/pinned-print from Go's strconv.IsPrint; edit")
	fmt.Println("  # nothing here. The runes strconv.Quote escapes, as ranges: each is")
	fmt.Println("  # twelve hex digits, the first rune and the last, in order.")
	fmt.Println()
	fmt.Printf("  def count(): integer do %d end\n", count)
	fmt.Println()
	fmt.Println("  def ranges(): string do")
	fmt.Printf("    %q\n", ranges.String())
	fmt.Println("  end")
	fmt.Println("end")
}
