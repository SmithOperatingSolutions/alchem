#!/usr/bin/env python3
"""Regenerate implementations/alchem/native-enumerable-data.alc: which
parameters of the pinned library's functions are written enum[...] in its
registrations (compiler/syntax/*.go, lib and libAlso). Not used by normal
builds.

The pinned checker types an argument for such a parameter with no expected
type unless it is the literal [] (library(), compiler/syntax/library.go), so
a value that needs its type from its context (Enum.reverse(Enum.reverse([])),
Map.new([{"a", []}])) is rejected there; native-enumerable.alc does the same
from this table. A row is the length of the name, the name (Module.function),
the number of parameters and a bit for each enum parameter; where overloads
of one name and arity disagree, only the parameters all of them write so."""
from pathlib import Path
import collections
import re

ROOT=Path(__file__).resolve().parents[1]


def rows():
    upstream=next((ROOT/'.cache/gomod/github.com/!smith!operating!solutions').glob('alchem@*'))
    found=collections.defaultdict(list)
    for path in sorted((upstream/'compiler/syntax').glob('*.go')):
        if path.name.endswith('_test.go'):continue
        for match in re.finditer(r'\blib(?:Also|Hidden)?\(\s*"([^"]+)",\s*"([^"]*)"',path.read_text()):
            name,signature=match.group(1),match.group(2)
            parts=[];depth=0;current=''
            for ch in signature.split('->')[0].strip():
                depth+=(ch=='[')-(ch==']')
                if ch==',' and depth==0:parts.append(current.strip());current=''
                else:current+=ch
            if current.strip():parts.append(current.strip())
            assert all('enum[' not in part or part.startswith('enum[') for part in parts),(name,parts)
            found[(name,len(parts))].append(sum(1<<index for index,part in enumerate(parts) if part.startswith('enum[')))
    out=[]
    for (name,arity),masks in sorted(found.items()):
        mask=masks[0]
        for other in masks[1:]:mask&=other
        if mask and '.' in name:
            assert len(name)<256 and arity<8 and mask<256,(name,arity)
            out.append((name,arity,mask))
    return out


def generate():
    raw=bytearray()
    for name,arity,mask in rows():raw+=bytes([len(name)])+name.encode()+bytes([arity,mask])
    raw+=b'\0'
    pieces=[];names=[]
    for i in range(0,len(raw),384):
        name=f'en_part_{i//384}';names.append(name)
        items=['b['+','.join(map(str,raw[j:min(j+128,i+384)]))+']' for j in range(i,min(i+384,len(raw)),128)]
        pieces.append(f'  def {name}(): bytes do '+(items[0] if len(items)==1 else 'nc_join('+','.join(items+['b[]']*(3-len(items)))+')')+' end\n')
    level=0
    while len(names)>1:
        merged=[]
        for i in range(0,len(names),3):
            group=names[i:i+3];name=f'en_group_{level}_{i//3}';merged.append(name)
            pieces.append(f'  def {name}(): bytes do nc_join('+','.join([part+'()' for part in group]+['b[]']*(3-len(group)))+') end\n')
        names=merged;level+=1
    return ('defmodule NativeEnumerableData do\n  # Generated by scripts/generate-enumerable-params.py from the pinned library registrations.\n'+''.join(pieces)+
            f'  def en_table(): bytes do {names[0]}() end\n  # Native smoke test; generated table of enum parameters.\n  def main() do System.halt(0) end\nend\n'),len(rows())


if __name__=='__main__':
    text,count=generate()
    (ROOT/'implementations/alchem/native-enumerable-data.alc').write_text(text)
    print(f'enum parameters: {count} library functions')
