const byteValueMessage = "E_RUNTIME_BYTE: expected byte value 0..255\n"

func emitPack(code *bytes.Buffer, args []int, heapGuards, byteGuards *[]int) {
	for _, arg := range args {
		functionSlot(code, 0x8b, 0, arg)
		code.Write([]byte{0x48, 0x3d, 0xff, 0, 0, 0, 0x0f, 0x87})
		*byteGuards = append(*byteGuards, code.Len())
		imm32(code, 0)
	}
	charge := (len(args) + 15) &^ 7
	code.Write([]byte{0x4d, 0x89, 0xe3, 0x49, 0x81, 0xc3})
	imm32(code, charge)
	code.Write([]byte{0x4d, 0x39, 0xeb, 0x0f, 0x87})
	*heapGuards = append(*heapGuards, code.Len())
	imm32(code, 0)
	code.Write([]byte{0x4c, 0x89, 0xe2, 0x4d, 0x89, 0xdc, 0x48, 0xc7, 0x02})
	imm32(code, len(args))
	for i, arg := range args {
		functionSlot(code, 0x8b, 0, arg)
		code.Write([]byte{0x88, 0x82})
		imm32(code, 8+i)
	}
	code.Write([]byte{0x48, 0x89, 0xd0})
}
