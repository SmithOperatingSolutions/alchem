const allocationMessage = "E_RUNTIME_ALLOC: byte allocation failed or limit exceeded\n"

func emitArenaInit(code *bytes.Buffer, guards *[]int, arenaBytes int) {
	if arenaBytes > 1<<30 {
		// A budget past 1 GiB is reserved lazily (MAP_NORESERVE), or the
		// largest half of it the system grants down to 1 GiB.
		code.Write([]byte{0x49, 0xbd})
		_ = binary.Write(code, binary.LittleEndian, uint64(arenaBytes))
		code.Write([]byte{0xb8, 9, 0, 0, 0, 0x31, 0xff, 0x4c, 0x89, 0xee, 0xba, 3, 0, 0, 0, 0x41, 0xba, 0x22, 0x40, 0, 0, 0x49, 0xc7, 0xc0, 0xff, 0xff, 0xff, 0xff, 0x45, 0x31, 0xc9, 0x0f, 0x05, 0x48, 0x3d, 0x01, 0xf0, 0xff, 0xff, 0x72, 17, 0x49, 0xd1, 0xed, 0x49, 0x81, 0xfd, 0, 0, 0, 0x40, 0x73, 0xcb, 0xe9})
		*guards = append(*guards, code.Len())
		imm32(code, 0)
		code.Write([]byte{0x49, 0x89, 0xc4, 0x49, 0x01, 0xc5})
		return
	}
	code.Write([]byte{0xb8, 9, 0, 0, 0, 0x31, 0xff, 0xbe})
	imm32(code, arenaBytes)
	code.Write([]byte{0xba, 3, 0, 0, 0, 0x41, 0xba, 0x22, 0, 0, 0, 0x49, 0xc7, 0xc0, 0xff, 0xff, 0xff, 0xff, 0x45, 0x31, 0xc9, 0x0f, 0x05, 0x48, 0x3d, 0x01, 0xf0, 0xff, 0xff, 0x0f, 0x83})
	*guards = append(*guards, code.Len())
	imm32(code, 0)
	code.Write([]byte{0x49, 0x89, 0xc4, 0x4c, 0x8d, 0xa8})
	imm32(code, arenaBytes)
}
