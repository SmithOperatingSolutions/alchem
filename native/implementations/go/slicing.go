package main

import "bytes"

func emitByteSlice(code *bytes.Buffer, buffer, index, count int, heapGuards *[]int) error {
	functionSlot(code, 0x8b, 7, buffer)
	functionSlot(code, 0x8b, 6, index)
	functionSlot(code, 0x8b, 2, count)
	code.Write([]byte{0x48, 0x85, 0xd2, 0x0f, 0x88})
	negative := code.Len()
	imm32(code, 0)
	code.Write([]byte{0x48, 0x8b, 0x0f, 0x48, 0x85, 0xf6, 0x79, 3, 0x48, 1, 0xce, 0x48, 0x39, 0xce, 0x73, 17, 0x48, 0x29, 0xf1, 0x48, 0x39, 0xca, 0x48, 0x0f, 0x47, 0xd1, 0x48, 0x8d, 0x74, 0x37, 8, 0xeb, 6, 0x31, 0xd2, 0x48, 0x8d, 0x77, 8, 0x4c, 0x8d, 0x5a, 15, 0x49, 0x83, 0xe3, 0xf8, 0x4d, 1, 0xe3, 0x4d, 0x39, 0xeb, 0x0f, 0x87})
	*heapGuards = append(*heapGuards, code.Len())
	imm32(code, 0)
	code.Write([]byte{0x4c, 0x89, 0xe0, 0x4d, 0x89, 0xdc, 0x48, 0x89, 0x10, 0x48, 0x8d, 0x78, 8, 0x48, 0x89, 0xd1, 0xfc, 0xf3, 0xa4, 0xe9})
	done := code.Len()
	imm32(code, 0)
	if err := emitFailureMessage(code, []int{negative}, "E_RUNTIME_SLICE: expected nonnegative count\n", 73); err != nil {
		return err
	}
	return patchFlowJump(code, done, code.Len())
}
