//! One fresh bounded byte copy, with overflow-safe index/count normalization.
use super::{flow::patch, functions::slot, imm32, runtime::finish_message, Result};
pub(super) fn slice(
    code: &mut Vec<u8>,
    buffer: usize,
    index: usize,
    count: usize,
    heap_guards: &mut Vec<usize>,
) -> Result<()> {
    slot(code, 0x8b, 7, buffer);
    slot(code, 0x8b, 6, index);
    slot(code, 0x8b, 2, count);
    code.extend_from_slice(&[0x48, 0x85, 0xd2, 0x0f, 0x88]);
    let negative = code.len();
    imm32(code, 0);
    code.extend_from_slice(&[
        0x48, 0x8b, 0x0f, 0x48, 0x85, 0xf6, 0x79, 3, 0x48, 1, 0xce, 0x48, 0x39, 0xce, 0x73, 17,
        0x48, 0x29, 0xf1, 0x48, 0x39, 0xca, 0x48, 0x0f, 0x47, 0xd1, 0x48, 0x8d, 0x74, 0x37, 8,
        0xeb, 6, 0x31, 0xd2, 0x48, 0x8d, 0x77, 8, 0x4c, 0x8d, 0x5a, 15, 0x49, 0x83, 0xe3, 0xf8,
        0x4d, 1, 0xe3, 0x4d, 0x39, 0xeb, 0x0f, 0x87,
    ]);
    heap_guards.push(code.len());
    imm32(code, 0);
    code.extend_from_slice(&[
        0x4c, 0x89, 0xe0, 0x4d, 0x89, 0xdc, 0x48, 0x89, 0x10, 0x48, 0x8d, 0x78, 8, 0x48, 0x89,
        0xd1, 0xfc, 0xf3, 0xa4, 0xe9,
    ]);
    let done = code.len();
    imm32(code, 0);
    finish_message(
        code,
        &[negative],
        "E_RUNTIME_SLICE: expected nonnegative count\n",
        73,
    )?;
    let end = code.len();
    patch(code, done, end)
}
