//! Bounded process-lifetime immutable byte construction in a separate RW arena.
use super::{functions::slot, imm32};
pub(super) fn init(code: &mut Vec<u8>, guards: &mut Vec<usize>, arena_bytes: usize) {
    if arena_bytes > 1 << 30 {
        // A budget past 1 GiB is reserved lazily (MAP_NORESERVE), or the
        // largest half of it the system grants down to 1 GiB.
        code.extend_from_slice(&[0x49, 0xbd]);
        code.extend_from_slice(&(arena_bytes as u64).to_le_bytes());
        code.extend_from_slice(&[
            0xb8, 9, 0, 0, 0, 0x31, 0xff, 0x4c, 0x89, 0xee, 0xba, 3, 0, 0, 0, 0x41, 0xba, 0x22,
            0x40, 0, 0, 0x49, 0xc7, 0xc0, 0xff, 0xff, 0xff, 0xff, 0x45, 0x31, 0xc9, 0x0f, 0x05,
            0x48, 0x3d, 0x01, 0xf0, 0xff, 0xff, 0x72, 17, 0x49, 0xd1, 0xed, 0x49, 0x81, 0xfd, 0, 0,
            0, 0x40, 0x73, 0xcb, 0xe9,
        ]);
        guards.push(code.len());
        imm32(code, 0);
        code.extend_from_slice(&[0x49, 0x89, 0xc4, 0x49, 0x01, 0xc5]);
        return;
    }
    code.extend_from_slice(&[0xb8, 9, 0, 0, 0, 0x31, 0xff, 0xbe]);
    imm32(code, arena_bytes);
    code.extend_from_slice(&[
        0xba, 3, 0, 0, 0, 0x41, 0xba, 0x22, 0, 0, 0, 0x49, 0xc7, 0xc0, 0xff, 0xff, 0xff, 0xff,
        0x45, 0x31, 0xc9, 0x0f, 0x05, 0x48, 0x3d, 0x01, 0xf0, 0xff, 0xff, 0x0f, 0x83,
    ]);
    guards.push(code.len());
    imm32(code, 0);
    code.extend_from_slice(&[0x49, 0x89, 0xc4, 0x4c, 0x8d, 0xa8]);
    imm32(code, arena_bytes);
}
pub(super) fn concat(code: &mut Vec<u8>, lhs: usize, rhs: usize, limit: usize, guards: &mut Vec<usize>) {
    slot(code, 0x8b, 6, lhs);
    slot(code, 0x8b, 2, rhs);
    code.extend_from_slice(&[
        0x48, 0x8b, 0x0e, 0x4c, 0x8b, 0x02, 0x49, 0x89, 0xc9, 0x4d, 0x01, 0xc1, 0x49, 0x81, 0xf9,
    ]);
    imm32(code, limit);
    code.extend_from_slice(&[0x0f, 0x87]);
    guards.push(code.len());
    imm32(code, 0);
    code.extend_from_slice(&[
        0x4d, 0x8d, 0x51, 0x0f, 0x49, 0x83, 0xe2, 0xf8, 0x4d, 0x89, 0xe3, 0x4d, 0x01, 0xd3, 0x4d,
        0x39, 0xeb, 0x0f, 0x87,
    ]);
    guards.push(code.len());
    imm32(code, 0);
    code.extend_from_slice(&[
        0x4c, 0x89, 0xe0, 0x4d, 0x89, 0xdc, 0x4c, 0x89, 0x08, 0x48, 0x8d, 0x78, 8, 0x48, 0x83,
        0xc6, 8, 0xfc, 0xf3, 0xa4, 0x48, 0x89, 0xd6, 0x48, 0x83, 0xc6, 8, 0x4c, 0x89, 0xc1, 0xf3,
        0xa4,
    ]);
}

pub(super) fn pack(
    code: &mut Vec<u8>,
    args: &[usize],
    heap_guards: &mut Vec<usize>,
    byte_guards: &mut Vec<usize>,
) {
    for arg in args {
        slot(code, 0x8b, 0, *arg);
        code.extend_from_slice(&[0x48, 0x3d, 0xff, 0, 0, 0, 0x0f, 0x87]);
        byte_guards.push(code.len());
        imm32(code, 0);
    }
    let charge = (args.len() + 15) & !7;
    code.extend_from_slice(&[0x4d, 0x89, 0xe3, 0x49, 0x81, 0xc3]);
    imm32(code, charge);
    code.extend_from_slice(&[0x4d, 0x39, 0xeb, 0x0f, 0x87]);
    heap_guards.push(code.len());
    imm32(code, 0);
    code.extend_from_slice(&[0x4c, 0x89, 0xe2, 0x4d, 0x89, 0xdc, 0x48, 0xc7, 0x02]);
    imm32(code, args.len());
    for (i, arg) in args.iter().enumerate() {
        slot(code, 0x8b, 0, *arg);
        code.extend_from_slice(&[0x88, 0x82]);
        imm32(code, 8 + i);
    }
    code.extend_from_slice(&[0x48, 0x89, 0xd0]);
}
