package compiler

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/SmithOperatingSolutions/alchem/compiler/ast"
)

// LockName is the file, beside a program's entry file, that records the
// content hash of every remote package and Go module the program uses.
const LockName = "alchem.lock"

const lockHeader = "# Generated by alchem. Records the content of remote packages and Go modules; commit this file.\n"

// lockFile is the parsed lock: package hashes by "path version", and the Go
// checksum lines of required modules.
type lockFile struct {
	packages map[string]string
	modules  []string
	text     string
}

func readLock(entry string) (*lockFile, error) {
	lock := &lockFile{packages: map[string]string{}}
	data, err := os.ReadFile(filepath.Join(filepath.Dir(entry), LockName))
	if os.IsNotExist(err) {
		return lock, nil
	}
	if err != nil {
		return nil, err
	}
	lock.text = string(data)
	for number, line := range strings.Split(lock.text, "\n") {
		fields := strings.Fields(line)
		switch {
		case len(fields) == 0 || strings.HasPrefix(line, "#"):
		case len(fields) == 4 && fields[0] == "package":
			lock.packages[fields[1]+" "+fields[2]] = fields[3]
		case len(fields) == 4 && fields[0] == "module":
			lock.modules = append(lock.modules, strings.Join(fields[1:], " "))
		default:
			return nil, fmt.Errorf("%s:%d: unrecognized line", LockName, number+1)
		}
	}
	return lock, nil
}

// moduleSums reads the checksum lines Go recorded for a prepared module.
func moduleSums(dir string) []string {
	data, _ := os.ReadFile(filepath.Join(dir, "go.sum"))
	sums := []string{}
	for _, line := range strings.Split(string(data), "\n") {
		if strings.TrimSpace(line) != "" {
			sums = append(sums, strings.TrimSpace(line))
		}
	}
	return sums
}

// syncLock checks a program against its lock file and brings the file up to
// date. A remote package whose content differs from the locked hash is an
// error. sums are the Go checksum lines of the prepared module, or nil when
// the module was not prepared, in which case the locked ones are kept. With
// locked set nothing is written, and anything the lock lacks is an error.
func syncLock(program ast.Program, lock *lockFile, sums []string, locked bool) error {
	stale := func(what string) error {
		return fmt.Errorf("%s has no entry for %s; run without --locked to update it", LockName, what)
	}
	lines := []string{}
	for _, remote := range program.Remotes {
		key := remote.Path + " " + remote.Version
		switch recorded, ok := lock.packages[key]; {
		case ok && recorded != remote.Sum:
			return fmt.Errorf("%s@%s does not match %s: locked %s, fetched %s", remote.Path, remote.Version, LockName, recorded, remote.Sum)
		case !ok && locked:
			return stale(remote.Path + "@" + remote.Version)
		}
		lines = append(lines, "package "+key+" "+remote.Sum)
	}
	if sums == nil {
		sums = lock.modules
	}
	known := map[string]bool{}
	for _, line := range lock.modules {
		known[line] = true
	}
	for _, line := range sums {
		if locked && !known[line] {
			return stale("Go module " + line)
		}
		lines = append(lines, "module "+line)
	}
	if locked {
		return nil
	}
	sort.Strings(lines)
	text := ""
	if len(lines) > 0 {
		text = lockHeader + strings.Join(lines, "\n") + "\n"
	}
	path := filepath.Join(filepath.Dir(program.Source), LockName)
	if text == lock.text {
		return nil
	}
	if text == "" {
		return os.Remove(path)
	}
	return os.WriteFile(path, []byte(text), 0644)
}
